#!/usr/bin/env bash
# Обёртка над `docker compose` для стека витрины и кабинета.
#
# ЗАЧЕМ ОНА СУЩЕСТВУЕТ. Домен объявлен ОДИН раз — в `/srv/broker/proxy/.env`.
# Компоуз подставляет переменные только из файлов, которые ему названы, и
# своего `.env` ему мало: в нём лежат секреты стека, а домена в нём нет и
# не должно быть. Два `--env-file` и есть механизм, который держит домен в
# одном месте.
#
# Запустишь голым `docker compose` — переменные не подставятся, адреса
# соберутся как `https://.`, образ стартует и будет уверенно вести
# посетителя в никуда. Поэтому обёртка, а не строчка в README: указание,
# которое надо помнить, однажды не вспомнят.
#
# Р-456 B (Vault): KYC-секреты (S3/MinIO) доставляются OpenBao через
# Vault Agent, который рендерит ../vault/rendered/.env.kyc. Этот файл
# добавляется ПОСЛЕДНИМ --env-file, поэтому его значения ПЕРЕКРЫВАЮТ
# одноимённые из .env. Если файла нет (OpenBao не поднят/запечатан, агент
# не отрендерил) — он просто не подключается, и стек берёт значения из
# базового .env (fallback). То есть источник KYC-ключей — OpenBao, но
# недоступность хранилища не роняет витрину: урок прод-CRM про
# неустановимость в проде наоборот — здесь мы НЕ делаем хранилище единой
# точкой отказа, пока офлайн-custody unseal-ключей не решён владельцем.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROXY_ENV="$HERE/../proxy/.env"
# Пароли кредлов шины лежат у шины и читаются оттуда: копия здесь была
# бы второй правдой, а разъехавшийся пароль даёт отказ при ближайшем
# ПЕРЕПОДКЛЮЧЕНИИ, а не при старте, — то есть в понедельник.
BUS_ENV="$HERE/../bus/.env"
OWN_ENV="$HERE/.env"
# KYC-секреты из OpenBao (Vault Agent рендерит сюда). Необязателен: нет —
# fallback на OWN_ENV. Подключается ПОСЛЕДНИМ, чтобы перекрывать .env.
VAULT_KYC_ENV="$HERE/../vault/rendered/.env.kyc"

for f in "$PROXY_ENV" "$BUS_ENV" "$OWN_ENV"; do
    [ -f "$f" ] || { echo "нет $f — без него подставлять нечего" >&2; exit 1; }
done

# Ревизия образов — из файла рядом, а не из головы. Одна строка, один
# коммит, оба образа. Менять выкатываемую версию = менять эту строку.
[ -f "$HERE/.revision" ] || { echo "нет $HERE/.revision — какую ревизию катим, неизвестно" >&2; exit 1; }
REV="$(tr -d ' \n\r' < "$HERE/.revision")"
case "$REV" in
    [0-9a-f]*) [ ${#REV} -eq 40 ] || { echo "в .revision не полный хеш коммита: «$REV»" >&2; exit 1; } ;;
    *) echo "в .revision не хеш коммита: «$REV»" >&2; exit 1 ;;
esac

ENV_ARGS=(--env-file "$PROXY_ENV" --env-file "$BUS_ENV" --env-file "$OWN_ENV")
if [ -f "$VAULT_KYC_ENV" ]; then
    ENV_ARGS+=(--env-file "$VAULT_KYC_ENV")
else
    echo "примечание: $VAULT_KYC_ENV нет — KYC-ключи берутся из .env (fallback OpenBao)" >&2
fi

exec env SITE_REVISION="$REV" docker compose "${ENV_ARGS[@]}" "$@"
