#!/usr/bin/env bash
# Проверка кода проверок. QA-03.
#
# Вопрос соседей был про типы: `tsconfig.json` исключал `*.test.ts`, и тестовый
# код не проверялся НИЧЕМ. В зоне deploy типов нет — зона целиком состоит из
# shell. Тот же вопрос здесь звучит так: **кто проверяет сами проверки**. До
# 19.10 ответ был «никто»: `backup.sh` и `verify-restore.sh` — это и есть наши
# проверки, и над ними не стояло ни линтера, ни прогона.
#
# Первый же запуск нашёл в них два настоящих дефекта (см. B-OPS-010,
# B-OPS-011), и оба — в коде, который печатает вердикт. Это ровно то, что
# записано правилом: инструмент проверки проверяют отдельно от того, что он
# проверяет.
#
# ПЕРЕЧЕНЬ ВЫВОДИТСЯ ИЗ ИСТОЧНИКА, А НЕ ВЕДЁТСЯ РУКАМИ. Список файлов, вбитый
# сюда руками, отставал бы от репозитория молча: новый скрипт просто не попал
# бы в прогон и об этом никто бы не узнал — это находка OPS-16, и повторять её
# в инструменте, написанном против неё, нельзя.
#
# Запуск:  bash ci/shellcheck.sh

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

# Уровень блокировки — warning. Ниже (note/style) сегодня 20 замечаний, и
# значительная часть из них — СОЗНАТЕЛЬНЫЙ код: SC2086 на `$REPOS`, `$PLAIN`,
# `$VOL_COVERED_OTHERWISE` — это намеренное словоделение списка. Поднять порог
# до note значило бы либо завесить скрипты директивами подавления, либо
# приучить читать красное как фон. Замечания ниже порога ПЕЧАТАЮТСЯ числом —
# чтобы их рост был виден, — но не блокируют, и это сказано вслух, а не
# умолчанием.
SEVERITY="${SHELLCHECK_SEVERITY:-warning}"

command -v shellcheck >/dev/null 2>&1 || {
  # Отсутствие инструмента — это НЕ «проверка пройдена». Молчаливый пропуск
  # здесь и есть способ, которым проверка перестаёт существовать.
  echo "ПРОВАЛ: shellcheck не установлен — проверка НЕ ВЫПОЛНЕНА, результат неизвестен" >&2
  exit 1
}

mapfile -t SCRIPTS < <(find . -path ./.git -prune -o -type f -name '*.sh' -print | sort)
N=${#SCRIPTS[@]}

# Пустой зелёный хуже отсутствующего: если find ничего не нашёл, значит сломан
# либо путь, либо сама эта проверка, а не «нарушений нет».
if [ "$N" -eq 0 ]; then
  echo "ПРОВАЛ: не найдено ни одного файла *.sh — проверять нечего, а должно быть что" >&2
  exit 1
fi

echo "=== shellcheck: порог $SEVERITY ==="
echo "осмотрено файлов *.sh (найдены обходом дерева, не списком): $N"
printf '  %s\n' "${SCRIPTS[@]}"
echo

# --- Перевод строки --------------------------------------------------------
#
# Скрипт с CRLF на Linux не работает: `set -euo pipefail\r` даёт «invalid
# option name», и прогон падает на первой строке с нечитаемой причиной.
#
# Сегодня это не проявляется по СОВПАДЕНИЮ: в индексе файлы лежат с LF, потому
# что у владельца машины стоит core.autocrlf=true. Это настройка машины, а не
# свойство репозитория, — коммит из другого инструмента занёс бы CRLF в индекс
# и сломал бы прогон на Linux. Поэтому свойство закреплено дважды: правилом в
# .gitattributes и этой проверкой. Правильное поведение по совпадению защитой
# не является.
CRLF=0
for f in "${SCRIPTS[@]}"; do
  if LC_ALL=C grep -qU $'\r' "$f"; then
    echo "ПРОВАЛ: $f содержит CR — на Linux такой скрипт не запустится" >&2
    CRLF=$((CRLF + 1))
  fi
done
if [ "$CRLF" -gt 0 ]; then
  echo "файлов с CRLF: $CRLF из $N" >&2
  exit 1
fi
echo "перевод строки: LF во всех $N файлах"
echo

# --- Замечания ниже порога: печатаем числом, не блокируем -------------------
BELOW=$(shellcheck -f gcc "${SCRIPTS[@]}" 2>/dev/null | grep -c . || true)
echo "замечаний всех уровней (note/style тоже): $BELOW — ниже порога, не блокируют"
echo

# --- Блокирующий прогон ----------------------------------------------------
if shellcheck -S "$SEVERITY" "${SCRIPTS[@]}"; then
  echo "=== shellcheck чисто: $N файлов, порог $SEVERITY ==="
else
  echo "=== shellcheck: НАЙДЕНЫ ЗАМЕЧАНИЯ уровня $SEVERITY и выше ===" >&2
  exit 1
fi
