#!/usr/bin/env bash
# Объявленный охват наблюдения совпадает с действительным. OPS-37, OPS-36.
#
# ЗАЧЕМ. 24.10 Prometheus работал с НУЛЁМ правил и отвечал на перезагрузку
# успехом (B-OPS-034). Ноль тревог выглядел как «всё спокойно», и отличить
# это изнутри было нечем: проверка, не проверившая ничего, неотличима от
# проверки, не нашедшей нарушений.
#
# Лекарство — проверка объявляет, СКОЛЬКО она проверила. В `pravila.yml`
# заведена тревога `PravilZagruzhenoMenshe` с порогом-числом. Но число,
# вбитое в правило руками, отстаёт от файла молча — и отстаёт ровно в ту
# сторону, в какую файл растёт: добавили правило, порог прежний, тревога
# больше не ловит потерю одного правила. Сторож, ослабевающий сам собой,
# хуже отсутствующего, потому что выглядит стоящим.
#
# Поэтому число сверяется механизмом. Здесь.
#
# Запуск:  bash ci/ohvat-pravil.sh

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PRAVILA="${1:-$ROOT/server/monitoring/conf/pravila.yml}"

if [ ! -f "$PRAVILA" ]; then
    # Отсутствие файла — это НЕ «ноль правил, всё сошлось».
    echo "ПРОВАЛ: нет $PRAVILA — проверка НЕ ВЫПОЛНЕНА, охват неизвестен" >&2
    exit 1
fi

# Действительное: сколько правил в файле.
# `grep -c` на отсутствии совпадений возвращает 1, и под `set -e` это
# уронило бы скрипт раньше, чем он успеет сказать, ЧТО именно не так.
fakt=$(grep -c '^ *- alert:' "$PRAVILA" || true)

# Объявленное: порог в самой тревоге об охвате.
# Берём из выражения, а не из комментария: комментарий — не механизм.
obyavleno=$(sed -n 's/^ *expr: *sum(prometheus_rule_group_rules) *< *\([0-9][0-9]*\) *$/\1/p' "$PRAVILA")

if [ -z "$obyavleno" ]; then
    echo "ПРОВАЛ: в $PRAVILA нет тревоги об охвате (sum(prometheus_rule_group_rules) < N)." >&2
    echo "        Без неё ноль загруженных правил снова станет тишиной." >&2
    exit 1
fi

if [ "$(printf '%s\n' "$obyavleno" | grep -c .)" -ne 1 ]; then
    echo "ПРОВАЛ: порогов охвата несколько — непонятно, какой из них правда:" >&2
    printf '  %s\n' $obyavleno >&2
    exit 1
fi

echo "правил в файле:      $fakt"
echo "объявлено в тревоге: $obyavleno"

if [ "$fakt" -ne "$obyavleno" ]; then
    echo "ПРОВАЛ: порог тревоги об охвате ($obyavleno) разошёлся с числом правил ($fakt)." >&2
    echo "        Поправьте expr в PravilZagruzhenoMenshe — иначе тревога" >&2
    echo "        перестанет ловить потерю $((fakt - obyavleno)) правил(а)." >&2
    exit 1
fi

echo "ОХВАТ СОШЁЛСЯ: $fakt правил, порог $obyavleno"
