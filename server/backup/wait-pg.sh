#!/bin/bash
# Ждёт НАСТОЯЩЕЙ готовности базы в контейнере.
#
# pg_isready отвечает «готов» ещё во время начальной настройки: postgres
# поднимается, выполняет сценарии инициализации и ПЕРЕЗАПУСКАЕТСЯ. Проверка,
# попавшая в это окно, проходит — а следующая команда падает с «система
# завершает работу». Поэтому ждём двух подряд удачных настоящих запросов,
# а не одного ответа службы.
set -eu
c="$1"; u="${2:-postgres}"; ok=0
for i in $(seq 1 60); do
  if docker exec "$c" psql -U "$u" -tAc "select 1" >/dev/null 2>&1; then
    ok=$((ok+1)); [ "$ok" -ge 2 ] && exit 0
  else
    ok=0
  fi
  sleep 2
done
echo "база $c не поднялась за 120 с" >&2; exit 1
