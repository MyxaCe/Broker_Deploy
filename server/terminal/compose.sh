#!/usr/bin/env bash
# Обёртка над `docker compose` для стека терминала.
#
# ЗАЧЕМ ОНА СУЩЕСТВУЕТ. Домен объявлен ОДИН раз — в `/srv/broker/proxy/.env`.
# Компоуз подставляет переменные только из файлов, которые ему названы, и
# своего `.env` ему мало: в нём лежат секреты стека, а домена в нём нет и
# не должно быть. Два `--env-file` и есть механизм, который держит домен в
# одном месте.
#
# Запустишь голым `docker compose` — переменные не подставятся, адреса
# соберутся как `https://.`, образ стартует и будет уверенно вести
# посетителя в никуда. Поэтому обёртка, а не строчка в README: указание,
# которое надо помнить, однажды не вспомнят.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROXY_ENV="$HERE/../proxy/.env"
OWN_ENV="$HERE/.env"

for f in "$PROXY_ENV" "$OWN_ENV"; do
    [ -f "$f" ] || { echo "нет $f — без него подставлять нечего" >&2; exit 1; }
done

# Ревизия образов — из файла рядом, а не из головы. Одна строка, один
# коммит, оба образа. Менять выкатываемую версию = менять эту строку.
[ -f "$HERE/.revision" ] || { echo "нет $HERE/.revision — какую ревизию катим, неизвестно" >&2; exit 1; }
REV="$(tr -d ' \n\r' < "$HERE/.revision")"
case "$REV" in
    [0-9a-f]*) [ ${#REV} -eq 40 ] || { echo "в .revision не полный хеш коммита: «$REV»" >&2; exit 1; } ;;
    *) echo "в .revision не хеш коммита: «$REV»" >&2; exit 1 ;;
esac

exec env TERMINAL_REVISION="$REV" docker compose \
    --env-file "$PROXY_ENV" --env-file "$OWN_ENV" "$@"
